import asyncio
from playwright.async_api import async_playwright
B="http://localhost:8765/"
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path="/usr/bin/google-chrome")
        ctx = await b.new_context(viewport={"width":1100,"height":900})
        await ctx.add_init_script(path="/home/claude/hubtest/mock2.js")
        async def priv(route):
            await route.fulfill(path="/home/claude/private/"+route.request.url.split("/__private/")[1], content_type="application/json")
        await ctx.route("**/__private/**", priv)
        pg = await ctx.new_page(); errs=[]; pg.on("pageerror", lambda e: errs.append(str(e)))
        pg.on("dialog", lambda d: asyncio.ensure_future(d.accept()))
        await pg.goto(B+"index.html"); await pg.evaluate("localStorage.clear(); localStorage.setItem('mockuser','S2')")
        await pg.goto(B+"student.html"); await pg.wait_for_selector(".topic-card")
        await pg.screenshot(path="/home/claude/lab_list.png")
        await pg.click(".topic-card"); await pg.wait_for_selector("#c1 .opt")
        print("url", pg.url)
        await pg.click("#c1 .q >> nth=0 >> .opt >> nth=1")
        await pg.click("#c1 .q >> nth=1 >> .opt >> nth=0")
        await pg.fill("[data-save=c1-g0]", "revive")
        await pg.fill("[data-save=c1-t0]", "His unorthodox policy failed to deliver prosperity.")
        await pg.fill("[data-save=final-p]", "The article argues that the rich are the winners.")
        await pg.wait_for_timeout(2000)
        print("savestate", await pg.inner_text("#savestate"))
        # drop the device copy so the reload must come from the database draft
        await pg.evaluate("Object.keys(localStorage).filter(k=>k.startsWith('hh.lab')).forEach(k=>localStorage.removeItem(k))")
        await pg.reload(); await pg.wait_for_selector("#c1 .opt")
        print("restored gap:", await pg.input_value("[data-save=c1-g0]"), "| mc marked:", await pg.locator("#c1 .opt.right").count())
        await pg.click("#submitBtn"); await pg.wait_for_selector(".banner.ok")
        print("banner:", (await pg.inner_text(".banner.ok"))[:120])
        print("readonly:", await pg.get_attribute("[data-save=c1-t0]", "readonly"))
        await pg.screenshot(path="/home/claude/lab_top.png")
        await pg.locator("#chartWrap").scroll_into_view_if_needed(); await pg.screenshot(path="/home/claude/lab_chart.png")
        # teacher
        await pg.evaluate("localStorage.setItem('mockuser','T'); localStorage.setItem('hh.class','C3')")
        await pg.goto(B+"teacher.html"); await pg.wait_for_selector(".cell[data-st]")
        print("cell:", await pg.inner_text(".cell[data-st]"))
        await pg.click(".cell[data-st]"); await pg.wait_for_selector(".lab-ans")
        await pg.wait_for_timeout(500); await pg.screenshot(path="/home/claude/lab_review.png")
        await pg.click("#dclose"); await pg.click("#tabs [data-tab=topics]"); await pg.wait_for_selector("[data-upstate]")
        await pg.wait_for_timeout(500); print("upstate:", await pg.inner_text("[data-upstate]"))
        await pg.screenshot(path="/home/claude/lab_topics.png")
        await pg.goto(B+"reading.html#ielts-trumponomics/S2"); await pg.wait_for_selector(".banner.info")
        print("teacher view:", (await pg.inner_text(".banner.info"))[:100])
        print("errors:", errs); await b.close()
asyncio.run(main())
